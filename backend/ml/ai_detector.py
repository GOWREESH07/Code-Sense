import os
import sys
from pathlib import Path
from typing import Dict, Any, Optional
import joblib
import pandas as pd

from backend.ml.ai_features import AIFeatureExtractor

MODEL_PATH = Path(__file__).resolve().parent.parent / "models" / "ai_code_model.joblib"


class AICodeDetector:
    CAVEAT = "Estimated heuristically — not a definitive determination. Treat as a signal, not a verdict."

    def __init__(self):
        self.artifact = None
        self._load_or_train()

    def _load_or_train(self):
        if MODEL_PATH.exists():
            try:
                self.artifact = joblib.load(MODEL_PATH)
            except Exception as e:
                print(f"[AIDetector] Model load error ({e}), retraining...")
                self._train()
        else:
            self._train()

    def _train(self):
        from backend.ml.ai_train import train_ai_detector
        self.artifact = train_ai_detector()

    @property
    def model(self):
        return self.artifact["model"]

    def predict_file(self, content: str, language: str = "python") -> Dict[str, Any]:
        """
        Calculates the probability that the given code was generated by an AI assistant.
        Returns ai_generated_score (0.0 to 1.0) and confidence label ('low', 'medium', 'high').
        """
        lines = [line for line in content.splitlines() if line.strip()]
        loc = len(lines)

        features = AIFeatureExtractor.extract_features(content, language)
        X = pd.DataFrame([features])[AIFeatureExtractor.FEATURE_NAMES]

        prob = float(self.model.predict_proba(X)[0][1])

        # Confidence calculation based on file size and distance from 0.5 decision boundary
        dist = abs(prob - 0.5)
        if loc < 15:
            confidence = "low"
        elif dist < 0.15:
            confidence = "low"
        elif loc < 35 or dist < 0.25:
            confidence = "medium"
        else:
            confidence = "high"

        return {
            "ai_generated_score": round(prob, 3),
            "confidence": confidence,
            "loc": loc,
            "features": features,
            "caveat": self.CAVEAT,
        }


ai_detector = AICodeDetector()
